CREATE OR REPLACE FUNCTION public.normalize_phone(p text)
 RETURNS text
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO ''
AS $function$
declare s text; d text; intl boolean;
begin
  if p is null then return null; end if;
  s := btrim(p);
  if s = '' or s !~ '^[+0-9 ()\-.]+$' then return null; end if;
  intl := s ~ '^(\+|00)';
  d := regexp_replace(s, '\D', '', 'g');
  if s ~ '^00' then d := substr(d, 3); end if;
  if d ~ '^234[789][01][0-9]{8}$' then return d; end if;                 -- 2348012345678 / +234 801 234 5678
  if d ~ '^2340[789][01][0-9]{8}$' then return '234' || substr(d, 5); end if; -- +234 (0)801 234 5678
  if intl then
    if d ~ '^234' then return null; end if;                                -- looked Nigerian but malformed
    if d ~ '^[1-9][0-9]{7,14}$' then return d; end if;                     -- other international, must start with + or 00
    return null;
  end if;
  if d ~ '^0[789][01][0-9]{8}$' then return '234' || substr(d, 2); end if; -- 08012345678
  if d ~ '^[789][01][0-9]{8}$' then return '234' || d; end if;             -- 8012345678
  return null;
end $function$

