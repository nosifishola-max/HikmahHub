CREATE OR REPLACE FUNCTION public.guard_product()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare sens jsonb := '{}'::jsonb;
begin
  new.title := nullif(btrim(new.title), '');
  if auth.uid() is not null and not public.is_admin() then
    if tg_op = 'INSERT' then
      new.is_featured := false; new.review_note := null; new.reviewed_by := null; new.reviewed_at := null; new.pending_changes := null;
      new.status := 'draft';   -- every new listing starts as an unpublished draft; it is submitted once a title and an image exist
    else
      new.is_featured := old.is_featured; new.vendor_id := old.vendor_id; new.slug := old.slug;
      new.review_note := old.review_note; new.reviewed_by := old.reviewed_by; new.reviewed_at := old.reviewed_at; new.pending_changes := old.pending_changes;
      if old.status = 'hidden' then new.status := old.status;
      elsif new.status is distinct from old.status and new.status not in ('draft','pending') then
        raise exception 'Not allowed to set this listing status';
      end if;
      if old.status = 'approved' and new.status = 'approved' then
        if new.title is distinct from old.title then sens := sens || jsonb_build_object('title', new.title); end if;
        if new.description is distinct from old.description then sens := sens || jsonb_build_object('description', new.description); end if;
        if new.category_id is distinct from old.category_id then sens := sens || jsonb_build_object('category_id', new.category_id); end if;
        if new.listing_type is distinct from old.listing_type then sens := sens || jsonb_build_object('listing_type', new.listing_type); end if;
        if sens <> '{}'::jsonb then
          if sens ? 'title' and (new.title is null or char_length(new.title) < 2) then raise exception 'Enter a product name (at least 2 characters)'; end if;
          new.pending_changes := coalesce(old.pending_changes, '{}'::jsonb) || sens;
          new.title := old.title; new.description := old.description; new.category_id := old.category_id; new.listing_type := old.listing_type;
        end if;
      elsif old.status = 'approved' then
        new.pending_changes := null;
      end if;
    end if;
  end if;
  if new.status in ('pending','approved') and (new.title is null or char_length(new.title) < 2) then raise exception 'Enter a product name (at least 2 characters)'; end if;
  if new.status in ('pending','approved') and (tg_op = 'INSERT' or new.status is distinct from old.status) then
    if new.category_id is null then raise exception 'Choose a category before submitting'; end if;
    if new.price is null then raise exception 'Enter a price before submitting'; end if;
    if not exists (select 1 from public.product_images i where i.product_id = new.id) then raise exception 'Add at least one product image before submitting'; end if;
  end if;
  if new.is_featured and new.status <> 'approved' then new.is_featured := false; end if;
  return new;
end $function$

