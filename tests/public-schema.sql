CREATE OR REPLACE FUNCTION public.admin_set_vendor_status(p_vendor uuid, p_status vendor_status, p_reason text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v public.vendors; ev bigint; nid uuid;
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  select * into v from public.vendors where id = p_vendor for update;
  if v.id is null then raise exception 'Vendor not found'; end if;
  if v.status = p_status then raise exception 'This application is already %', p_status; end if;
  if not ((v.status = 'pending' and p_status in ('approved','rejected')) or (v.status = 'rejected' and p_status = 'approved')
       or (v.status = 'approved' and p_status = 'suspended') or (v.status = 'suspended' and p_status = 'approved')) then
    raise exception 'Cannot change a % application to %', v.status, p_status; end if;
  if p_status in ('rejected','suspended') and char_length(btrim(coalesce(p_reason,''))) < 3 then raise exception 'Please give a reason (at least 3 characters)'; end if;
  update public.vendors set status = p_status, is_verified = (p_status = 'approved'),
      rejection_reason = case when p_status in ('rejected','suspended') then btrim(p_reason) else null end,
      reviewed_by = auth.uid(), reviewed_at = now() where id = p_vendor;
  update public.profiles set role = case when p_status = 'approved' then 'vendor'::public.user_role else 'student'::public.user_role end where id = v.owner_id and role <> 'admin';
  insert into public.admin_actions (admin_id, action, target_type, target_id, details) values (auth.uid(), 'vendor_' || p_status::text, 'vendor', p_vendor, jsonb_build_object('reason', p_reason));
  if p_status in ('approved','rejected') then
    select id into ev from public.vendor_review_events where vendor_id = p_vendor order by id desc limit 1;
    insert into public.vendor_notifications (vendor_id, event_id, kind) values (p_vendor, ev, p_status::text) returning id into nid;
