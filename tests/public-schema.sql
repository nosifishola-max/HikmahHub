CREATE OR REPLACE FUNCTION public.admin_resolve_report(p_report uuid, p_status text, p_hide_target boolean DEFAULT false)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare r public.reports;
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  if p_status not in ('reviewing','resolved','dismissed') then raise exception 'Invalid status'; end if;
  update public.reports set status = p_status, resolved_by = auth.uid(), resolved_at = case when p_status <> 'reviewing' then now() end
    where id = p_report returning * into r;
  if r.id is null then raise exception 'Report not found'; end if;
  if p_hide_target then
    if r.target_type = 'product' then update public.products set status = 'hidden' where id = r.target_id;
    elsif r.target_type = 'store' then update public.vendors set status = 'suspended', is_verified = false where id = r.target_id;
    elsif r.target_type = 'deal' then update public.campus_deals set status = 'hidden' where id = r.target_id;
    elsif r.target_type = 'event' then update public.events set status = 'cancelled' where id = r.target_id;
    end if;
  end if;
  insert into public.admin_actions (admin_id, action, target_type, target_id, details)
    values (auth.uid(), 'report_' || p_status, r.target_type, r.target_id, jsonb_build_object('report', p_report, 'hidden', p_hide_target));
end $function$

CREATE OR REPLACE FUNCTION public.admin_review_product(p_product uuid, p_status moderation_status, p_note text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare cur public.moderation_status;
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  select status into cur from public.products where id = p_product for update;
  if cur is null then raise exception 'Listing not found'; end if;
  if p_status not in ('approved','rejected','hidden') then raise exception 'Invalid review status'; end if;
  if cur = p_status then raise exception 'This listing is already %', p_status; end if;
  if p_status in ('rejected','hidden') and char_length(btrim(coalesce(p_note,''))) < 3 then raise exception 'Please give a reason (at least 3 characters)'; end if;
  update public.products set status = p_status, review_note = case when p_status = 'approved' then null else btrim(p_note) end,
    reviewed_by = auth.uid(), reviewed_at = now(), pending_changes = case when p_status = 'approved' then null else pending_changes end,
    is_featured = is_featured and p_status = 'approved' where id = p_product;
  insert into public.admin_actions (admin_id, action, target_type, target_id, details) values (auth.uid(), 'product_' || p_status::text, 'product', p_product, jsonb_build_object('note', p_note));
end $function$

