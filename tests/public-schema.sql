CREATE OR REPLACE FUNCTION public.admin_review_changes(p_product uuid, p_approve boolean, p_note text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare pc jsonb;
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  select pending_changes into pc from public.products where id = p_product for update;
  if pc is null then raise exception 'No pending changes to review'; end if;
  if p_approve then
    update public.products set title = coalesce(pc->>'title', title), description = case when pc ? 'description' then pc->>'description' else description end,
      category_id = case when pc ? 'category_id' then (pc->>'category_id')::uuid else category_id end,
      listing_type = coalesce((pc->>'listing_type')::public.listing_type, listing_type), pending_changes = null, review_note = null, reviewed_by = auth.uid(), reviewed_at = now() where id = p_product;
  else
    if char_length(btrim(coalesce(p_note,''))) < 3 then raise exception 'Please give a reason (at least 3 characters)'; end if;
    update public.products set pending_changes = null, review_note = 'Your requested changes were not approved: ' || btrim(p_note), reviewed_by = auth.uid(), reviewed_at = now() where id = p_product;
  end if;
  insert into public.admin_actions (admin_id, action, target_type, target_id, details) values (auth.uid(), case when p_approve then 'changes_approved' else 'changes_rejected' end, 'product', p_product, jsonb_build_object('note', p_note));
end $function$

