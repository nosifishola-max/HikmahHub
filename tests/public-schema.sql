CREATE OR REPLACE FUNCTION public.assign_slug()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare base text; cand text; n int := 1; taken boolean; src text; j jsonb := to_jsonb(new);
begin
  if tg_table_name = 'vendors' then src := j->>'store_name'; else src := j->>'title'; end if;
  base := public.slugify(coalesce(nullif(j->>'slug', ''), src));
  cand := base;
  loop
    if tg_table_name = 'vendors' then
      select exists (select 1 from public.vendors where slug = cand and id <> new.id) into taken;
    elsif tg_table_name = 'products' then
      select exists (select 1 from public.products where vendor_id = (j->>'vendor_id')::uuid and slug = cand and id <> new.id) into taken;
    else
      select exists (select 1 from public.events where slug = cand and id <> new.id) into taken;
    end if;
    exit when not taken;
    n := n + 1; cand := base || '-' || n;
  end loop;
  new := jsonb_populate_record(new, jsonb_build_object('slug', cand));
  return new;
end $function$

CREATE OR REPLACE FUNCTION public.search_products(p_q text DEFAULT NULL::text, p_category uuid DEFAULT NULL::uuid, p_type listing_type DEFAULT NULL::listing_type, p_min numeric DEFAULT NULL::numeric, p_max numeric DEFAULT NULL::numeric, p_sort text DEFAULT 'newest'::text, p_limit integer DEFAULT 24, p_offset integer DEFAULT 0, p_seed text DEFAULT NULL::text)
 RETURNS TABLE(id uuid, title text, slug text, price numeric, availability availability_status, listing_type listing_type, store_name text, store_slug text, is_verified boolean, image_path text, created_at timestamp with time zone)
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  with f as (
    select p.id, p.title, p.slug, p.price, p.availability, p.listing_type, p.created_at, v.id as vid, v.store_name, v.slug as vslug, v.is_verified
    from public.products p join public.vendors v on v.id = p.vendor_id
    where p.status = 'approved' and v.status = 'approved'
      and (p_q is null or btrim(p_q) = '' or p.title ilike '%' || btrim(p_q) || '%' or p.description ilike '%' || btrim(p_q) || '%' or v.store_name ilike '%' || btrim(p_q) || '%'
           or exists (select 1 from public.categories c where c.id = p.category_id and c.name ilike '%' || btrim(p_q) || '%'))
      and (p_category is null or p.category_id = p_category or p.category_id in (select c.id from public.categories c where c.parent_id = p_category))
      and (p_type is null or p.listing_type = p_type)
      and (p_min is null or p.price >= p_min) and (p_max is null or p.price <= p_max)),
  r as (select f.*, case when p_sort = 'mixed' then row_number() over (partition by f.vid order by md5(coalesce(p_seed, '') || f.id::text)) end as rn from f),
  o as (select r.*, row_number() over (order by
      case when p_sort = 'mixed' then r.rn end asc,
      case when p_sort = 'mixed' then md5(coalesce(p_seed, '') || r.vid::text || r.rn::text) end asc,
      case when p_sort = 'price_asc' then r.price end asc, case when p_sort = 'price_desc' then r.price end desc,
      case when p_sort = 'oldest' then r.created_at end asc, r.created_at desc, r.id) as ord from r)
  select o.id, o.title, o.slug, o.price, o.availability, o.listing_type, o.store_name, o.vslug, o.is_verified,
    (select i.path from public.product_images i where i.product_id = o.id order by i.sort_order limit 1), o.created_at
  from o where o.ord > greatest(coalesce(p_offset, 0), 0) and o.ord <= greatest(coalesce(p_offset, 0), 0) + least(coalesce(p_limit, 24), 60)
  order by o.ord;
$function$

