CREATE OR REPLACE FUNCTION public.snapshot_weekly_rankings(p_week date DEFAULT (date_trunc('week'::text, now()))::date)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if auth.uid() is not null and not public.is_admin() then raise exception 'Admin only'; end if;
  delete from public.weekly_rankings where week_start = p_week;
  -- computed over trailing 7 days; run via admin or scheduled job
  insert into public.weekly_rankings (week_start, kind, entity_id, label, rank, score, metrics)
  select p_week, 'top_vendors', t.vendor_id, t.store_name, row_number() over (order by t.score desc, t.store_name), t.score,
    jsonb_build_object('store_views', t.store_views, 'product_views', t.product_views, 'whatsapp_clicks', t.whatsapp_clicks, 'saves', t.saves)
  from (
    with w as (select now() - interval '7 days' as since),
    sv as (select s.vendor_id, count(*) c from public.store_views s, w where s.created_at >= w.since group by 1),
    pv as (select p.vendor_id, count(*) c from public.product_views x join public.products p on p.id = x.product_id, w where x.created_at >= w.since group by 1),
    wc as (select c.vendor_id, count(*) c from public.whatsapp_clicks c, w where c.created_at >= w.since group by 1),
    sa as (select p.vendor_id, count(*) c from public.product_saves x join public.products p on p.id = x.product_id, w where x.created_at >= w.since group by 1)
    select v.id vendor_id, v.store_name,
      (coalesce(sv.c,0)+coalesce(pv.c,0)+5*coalesce(wc.c,0)+3*coalesce(sa.c,0))::numeric score,
      coalesce(sv.c,0) store_views, coalesce(pv.c,0) product_views, coalesce(wc.c,0) whatsapp_clicks, coalesce(sa.c,0) saves
    from public.vendors v left join sv on sv.vendor_id=v.id left join pv on pv.vendor_id=v.id
      left join wc on wc.vendor_id=v.id left join sa on sa.vendor_id=v.id where v.status='approved'
  ) t where t.score > 0 order by t.score desc limit 10;

  insert into public.weekly_rankings (week_start, kind, entity_id, label, rank, score, metrics)
  select p_week, 'trending_products', t.id, t.title, row_number() over (order by t.score desc, t.title), t.score,
    jsonb_build_object('views', t.views, 'saves', t.saves, 'whatsapp_clicks', t.wc)
  from (
    with w as (select now() - interval '7 days' as since),
    pv as (select x.product_id, count(*) c from public.product_views x, w where x.created_at >= w.since group by 1),
    sa as (select x.product_id, count(*) c from public.product_saves x, w where x.created_at >= w.since group by 1),
    wc as (select c.product_id, count(*) c from public.whatsapp_clicks c, w where c.product_id is not null and c.created_at >= w.since group by 1)
    select p.id, p.title, (coalesce(pv.c,0)+3*coalesce(sa.c,0)+5*coalesce(wc.c,0))::numeric score,
      coalesce(pv.c,0) views, coalesce(sa.c,0) saves, coalesce(wc.c,0) wc
    from public.products p join public.vendors v on v.id=p.vendor_id
      left join pv on pv.product_id=p.id left join sa on sa.product_id=p.id left join wc on wc.product_id=p.id
    where p.status='approved' and v.status='approved'
  ) t where t.score > 0 order by t.score desc limit 10;

  insert into public.weekly_rankings (week_start, kind, entity_id, label, rank, score, metrics)
  select p_week, 'most_wanted', null, t.term, row_number() over (order by t.score desc, t.term), t.score,
    jsonb_build_object('unfulfilled_searches', t.unfulfilled_searches, 'demand_requests', t.demand_requests)
  from (select * from public.get_most_wanted(7, 10)) t;
end $function$

